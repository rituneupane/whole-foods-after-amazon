"""Run tie-out tests and build the static dashboard data file.

Run from the repo root:  python analysis/build.py
- writes data/checks.csv
- writes docs/data.js (used by docs/index.html)
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)


def load(name, text=()):
    rows = list(csv.DictReader(open(P("data", name))))
    return [{k: (v if k in text or v == "" else float(v)) if k != "year" else int(v) for k, v in r.items()} for r in rows]


annual = load("wfm_annual.csv", text=("label", "source"))
category = load("category_mix.csv", text=("category", "note"))
channel = load("prime_channel.csv", text=("note",))
states = load("state_sales.csv", text=("state", "abbrev", "note"))
basket = load("price_basket.csv", text=("banner", "note"))

checks = []
def check(name, value, should, tol):
    checks.append(dict(check=name, value=round(value, 3), should_equal=round(should, 3),
                       result="PASS" if abs(value - should) <= tol else "FAIL"))

A = {r["year"]: r for r in annual}
for y, r in A.items():
    if r["yoy_pct"] != "":
        check(f"{y} YoY % recomputed", (r["store_sales_b"] / A[y - 1]["store_sales_b"] - 1) * 100, r["yoy_pct"], 0.15)
    cats = [c for c in category if c["year"] == y]
    check(f"{y} category shares = 100%", sum(c["share"] for c in cats), 1.0, 0.001)
    check(f"{y} category $ = store sales ($B)", sum(c["sales_b"] for c in cats), r["store_sales_b"], 0.02)
for c in channel:
    y = c["year"]
    check(f"{y} in-store = 10-K Physical stores ($B)", c["instore_b"], A[y]["store_sales_b"], 0.005)
    check(f"{y} in-store + pickup + delivery = store-fulfilled ($B)", c["instore_b"] + c["pickup_b"] + c["delivery_b"], c["store_fulfilled_b"], 0.011)
    check(f"{y} Prime + non-Prime = 100%", c["prime_share"] + c["nonprime_share"], 1.0, 0.001)
check("State store counts = 2026 store count", sum(s["stores"] for s in states), A[2026]["stores"], 0)
check("State sales shares = 100%", sum(s["sales_share"] for s in states), 1.0, 0.001)
check("State sales = 2026E store sales ($B)", sum(s["sales_b_2026e"] for s in states), A[2026]["store_sales_b"], 0.03)

with open(P("data", "checks.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(checks[0]), lineterminator="\n"); w.writeheader(); w.writerows(checks)
fails = [c for c in checks if c["result"] != "PASS"]
print(f"{len(checks)} checks, {len(fails)} failed")
for c in fails: print("FAIL", c)

with open(P("docs", "data.js"), "w") as f:
    f.write("// Generated by analysis/build.py from data/*.csv. Do not edit by hand.\n")
    for k, v in dict(ANNUAL=annual, CATEGORY=category, CHANNEL=channel, STATES=states, BASKET=basket).items():
        f.write(f"const {k} = {json.dumps(v)};\n")
